    <h1>Données personnelles</h1>

    <p>Dans le cadre de ses activités, Nantes Université collecte et traite des données personnelles de ses étudiants et de ses agents, dans le respect de la protection des données à caractère personnel.</p>
    <p>Conformément à la <strong>règlementation générale sur la protection des données de 2016 (RGPD)</strong> et à la <strong>loi Informatique et Libertés de 1978 modifiée</strong>, vous pouvez accéder aux données vous concernant, les rectifier, demander leur effacement ou exercer votre droit à la limitation du traitement de vos données.</p>

    <h2>Responsable de traitement</h2>
    <p>Nantes Université, 1 quai de Tourville, BP 13522, 44 035 Nantes Cedex 1.</p>

    <h2>Données collectées par OTTIS</h2>
    <p>L'application OTTIS traite les catégories de données suivantes :</p>
    <ul>
        <li><strong>Données d'authentification</strong> : identifiant institutionnel transmis par le service d'authentification centrale (CAS) de Nantes Université lors de la connexion ;</li>
        <li><strong>Contenus de session</strong> : transcriptions, traductions, messages du chat et notes générés pendant une intervention ;</li>
        <li><strong>Fichiers pédagogiques</strong> : présentations (PowerPoint, PDF) temporairement déposées pour être diffusées et sous-titrées ;</li>
        <li><strong>Mesure d'audience</strong> : statistiques de fréquentation anonymisées (analytics.univ-nantes.fr).</li>
    </ul>

    <h2>Finalités et bases légales</h2>
    <p>Ces traitements sont nécessaires à la fourniture du service de sous-titrage et de traduction en temps réel d'OTTIS, dans le cadre des missions d'enseignement de Nantes Université (mission d'intérêt public).</p>

    <h2>Durées de conservation</h2>
    <p>Les contenus de session et les fichiers déposés ont un caractère temporaire : ils sont conservés le temps de l'intervention puis purgés des espaces de stockage temporaires. Les données d'authentification ne sont conservées que le temps de la session de travail.</p>

    <h2>Sous-traitants et transferts</h2>
    <p>La traduction automatique est assurée par le service DeepL, dont les serveurs sont situés au sein de l'Union européenne. Aucun transfert de données hors de l'Union européenne n'est effectué.</p>

