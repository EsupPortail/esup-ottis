    <h1>Accessibilité</h1>

    <h2>Rappel de la loi</h2>
    <p>L'article 47 de la loi n° 2005-102 du 11 février 2005 pour l'égalité des droits et des chances, la participation et la citoyenneté des personnes handicapées fait de l'accessibilité une exigence pour tous les services de communication publique en ligne de l'État, des collectivités territoriales et des établissements publics qui en dépendent. Il stipule que les informations diffusées par ces services doivent être accessibles à tous.</p>
    <p>Nantes Université s'engage à rendre ses sites internet, intranet, extranet et ses progiciels accessibles conformément à l'article 47 de la loi n° 2005-102 du 11 février 2005.</p>

    <p>Cette déclaration d'accessibilité s'applique à l'application <strong>OTTIS</strong>.</p>

    <h2>État de conformité</h2>
    <p>OTTIS est <strong>partiellement conforme</strong> avec le référentiel général d'amélioration de l'accessibilité (RGAA), version 4.1.</p>
    <p>L'accessibilité est une contrainte de conception du projet : l'interface auditeur a été refondue selon le RGAA 4.1 et la migration de l'interface de conférence vise une conformité complète.</p>

    <h2>Résultats des tests</h2>
    <p>L'audit de conformité RGAA 4.1 de l'application est en cours. Les taux de conformité seront publiés sur cette page à l'issue de l'audit.</p>

    <h2>Contenus non accessibles</h2>
    <p>Les non-conformités éventuelles identifiées lors des audits en cours seront listées ici, par thématique et critère du RGAA.</p>

    <h2>Amélioration et contact</h2>
    <p>Si vous n'arrivez pas à accéder à un contenu ou à un service, vous pouvez contacter l'équipe du projet pour être orienté vers une alternative accessible ou obtenir le contenu sous une autre forme : <a href="mailto:accessibilite-numerique@univ-nantes.fr">accessibilite-numerique@univ-nantes.fr</a>.</p>

    <h2>Voie de recours</h2>
    <p>Cette procédure est à utiliser dans le cas suivant : vous avez signalé au responsable du site internet un défaut d'accessibilité qui vous empêche d'accéder à un contenu ou à un des services du portail et vous n'avez pas obtenu de réponse satisfaisante.</p>
    <ul>
        <li>Écrire un message au Défenseur des droits (<a href="https://www.defenseurdesdroits.fr">www.defenseurdesdroits.fr</a>) ;</li>
        <li>Contacter le délégué du Défenseur des droits dans votre région ;</li>
        <li>Envoyer un courrier par la poste (gratuit, ne pas mettre de timbre) : Défenseur des droits, Libre réponse 71120, 75343 Paris CEDEX 07.</li>
    </ul>

